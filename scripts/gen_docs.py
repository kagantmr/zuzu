#!/usr/bin/env python3
"""Generate the zuzu-docs reference pages from Doxygen XML.

Consumes the XML produced by ``make docs-site`` (Doxygen over the headers
listed in ``docs/doc-publish``) and writes Markdown for MkDocs under
``<out>/docs/reference``:

- ``syscalls/index.md``: the syscall table, grouped like ``zuzu.h``;
- ``syscalls/<name>.md``: one page per function in a ``syscalls_*`` group,
  syscalls (``@syscall_num``) and library helpers alike;
- one page per header in ``HEADERS`` (types, errors, syspage);
- ``sync/<name>.md``: one page per ``include/sync`` header;
- ``lib/<dir>/<name>.md``: one page per other header, and ``lib/index.md``
  listing them.

Names that Doxygen links (types, constants, functions) become links to the
page that documents them.

    make docs-site DOCS_OUT=../zuzu-docs

``--clean`` deletes generated pages that no longer have a source, ``--check``
only reports drift.
"""

from __future__ import annotations

import argparse
import copy
import os
import re
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

REF = Path("docs/reference")
SYSCALLS = REF / "syscalls"
SYNC = REF / "sync"
LIB = REF / "lib"
SINCE = "2.0"
AUTOGEN = "<!-- Generated by scripts/gen_docs.py in kagantmr/zuzu. Do not edit. -->"

HEADERS = {
    "include/types.h": (REF / "types.md", "Types"),
    "include/zuzu/err.h": (REF / "errors.md", "Errors"),
    "include/zuzu/syspage.h": (REF / "syspage.md", "Syspage"),
}
SYNC_SKIP = {"primitives.h"}
NO_PAGE = {"include/zuzu/zuzu.h", "include/svc_nums.h"}

GROUPS = [
    ("misc", "Basics"),
    ("handle", "Handles"),
    ("task", "Tasks"),
    ("space", "Spaces"),
    ("memory", "Memory and DMA"),
    ("ipc", "IPC"),
    ("event", "Events"),
]

STRUCTURED_TAGS = {"parameterlist", "simplesect", "xrefsect"}
ADMONITIONS = {"note", "warning", "attention", "remark", "pre", "post"}

LINKS: dict[str, tuple[Path, str]] = {}
CUR: Path = Path()


def link(name: str, text: str | None = None) -> str:
    text = text if text is not None else name
    target = LINKS.get(name)
    if target is None or (target[0] == CUR and not target[1]):
        return text
    page, anchor = target
    href = "" if page == CUR else os.path.relpath(page, CUR.parent)
    return f"[{text}]({href}{'#' + anchor if anchor else ''})"


# --------------------------------------------------------------------------
# Description -> Markdown
# --------------------------------------------------------------------------
def flatten(node: ET.Element | None) -> str:
    if node is None:
        return ""
    out: list[str] = []

    def walk(el: ET.Element) -> None:
        tag = el.tag
        if tag == "para":
            if el.text:
                out.append(el.text)
            for child in el:
                walk(child)
            out.append("\n\n")
        elif tag in ("computeroutput", "verbatim"):
            out.append(f"`{''.join(el.itertext())}`")
        elif tag in ("emphasis", "italic"):
            out.append(f"*{''.join(el.itertext())}*")
        elif tag in ("bold", "strong"):
            out.append(f"**{''.join(el.itertext())}**")
        elif tag == "ref":
            out.append(link("".join(el.itertext())))
        elif tag == "programlisting":
            lines = [_codeline(c) for c in el.findall("codeline")]
            out.append("\n```c\n" + "\n".join(lines) + "\n```\n\n")
        elif tag == "simplesect":
            pass
        elif tag in ("itemizedlist", "orderedlist"):
            out.append("\n\n")
            for i, item in enumerate(el.findall("listitem"), 1):
                bullet = "-" if tag == "itemizedlist" else f"{i}."
                out.append(f"{bullet} {_inline(item)}\n")
            out.append("\n")
        elif tag in ("parameterlist", "xrefsect"):
            pass
        else:
            if el.text:
                out.append(el.text)
            for child in el:
                walk(child)
        if el.tail:
            out.append(el.tail)

    if node.text:
        out.append(node.text)
    for child in node:
        walk(child)
    text = re.sub(r"[ \t]+\n", "\n", "".join(out))
    return re.sub(r"\n{3,}", "\n\n", text).strip()


def _codeline(cl: ET.Element) -> str:
    buf: list[str] = []

    def rec(el: ET.Element) -> None:
        if el.tag == "sp":
            buf.append(" ")
        if el.text:
            buf.append(el.text)
        for c in el:
            rec(c)
        if el.tail:
            buf.append(el.tail)

    if cl.text:
        buf.append(cl.text)
    for c in cl:
        rec(c)
    return "".join(buf)


def _inline(node: ET.Element | None) -> str:
    return re.sub(r"\s+", " ", flatten(node)).strip()


def _text(node: ET.Element | None) -> str:
    return re.sub(r"\s+", " ", "".join(node.itertext())).strip() if node is not None else ""


def _type(node: ET.Element | None) -> str:
    if node is None:
        return ""
    parts = [node.text or ""]
    for c in node:
        parts.append(link(_text(c), f"`{_text(c)}`") if c.tag == "ref" else _text(c))
        parts.append(c.tail or "")
    raw = "".join(parts).strip()
    return raw if "`" in raw and "[" in raw else (f"`{raw}`" if raw else "")


def _prose(dd: ET.Element | None) -> str:
    if dd is None:
        return ""
    clone = copy.deepcopy(dd)

    def strip(el: ET.Element) -> None:
        for child in list(el):
            if child.tag in STRUCTURED_TAGS:
                el.remove(child)
            else:
                strip(child)

    strip(clone)
    return flatten(clone)


def _desc(m: ET.Element) -> str:
    return " ".join(t for t in (_inline(m.find("briefdescription")),
                                _inline(m.find("detaileddescription"))) if t)


def _param_pairs(dd: ET.Element | None, kind: str) -> list[tuple[str, str, str]]:
    pairs: list[tuple[str, str, str]] = []
    if dd is None:
        return pairs
    for pl in dd.iter("parameterlist"):
        if pl.get("kind") != kind:
            continue
        for item in pl.findall("parameteritem"):
            names = list(item.iter("parametername"))
            direction = (names[0].get("direction") or "").replace(" ", "") if names else ""
            desc = _inline(item.find("parameterdescription"))
            pairs.append((", ".join(n.text or "" for n in names if n.text), direction, desc))
    return pairs


def _return(dd: ET.Element | None) -> str:
    if dd is None:
        return ""
    for ss in dd.iter("simplesect"):
        if ss.get("kind") == "return":
            return _inline(ss)
    return ""


def _admonitions(dd: ET.Element | None) -> list[str]:
    res: list[str] = []
    if dd is None:
        return res
    for ss in dd.iter("simplesect"):
        kind = ss.get("kind")
        if kind in ADMONITIONS:
            style = "warning" if kind in ("warning", "attention") else "note"
            res.append(f'!!! {style} "{kind.capitalize()}"\n    {_inline(ss)}')
    return res


def cell(s: str) -> str:
    return s.replace("|", "\\|").replace("\n", " ")


def md_table(headers: list[str], rows: list[tuple[str, ...]]) -> str:
    out = "| " + " | ".join(headers) + " |\n"
    out += "|" + "|".join("---" for _ in headers) + "|\n"
    for r in rows:
        out += "| " + " | ".join(cell(c) for c in r) + " |\n"
    return out.rstrip()


def proto_of(m: ET.Element) -> str:
    name = (m.findtext("name") or "").strip()
    if m.get("kind") == "define":
        params = [p.findtext("defname", "").strip() for p in m.findall("param")]
        return f"#define {name}({', '.join(params)})" if params else f"#define {name}"
    defn = (m.findtext("definition") or name).strip()
    defn = re.sub(r"^static\s+(inline\s+)?", "", defn)
    return f"{defn}{(m.findtext('argsstring') or '').strip()}"


def page_text(title: str, body: list[str]) -> str:
    return "\n".join([f"# {title}", "", AUTOGEN, "", *body]).rstrip() + "\n"


# --------------------------------------------------------------------------
# Enum values
# --------------------------------------------------------------------------
def _eval(expr: str, values: dict[str, int]) -> int | None:
    expr = re.sub(r"(?<=\d)[uUlL]+\b", "", expr)
    expr = re.sub(r"\b[A-Za-z_]\w*\b",
                  lambda mo: str(values[mo.group(0)]) if mo.group(0) in values else mo.group(0), expr)
    if not re.fullmatch(r"[\d\sxXa-fA-F()|&<>~+\-*]+", expr):
        return None
    try:
        return int(eval(expr, {"__builtins__": {}}, {}))
    except Exception:
        return None


def enum_values(xmldir: Path) -> dict[str, int]:
    values: dict[str, int] = {}
    for f in sorted(xmldir.glob("*_8h.xml")):
        for m in ET.parse(f).getroot().iter("memberdef"):
            if m.get("kind") == "define":
                v = _eval(_text(m.find("initializer")), values) if m.find("initializer") is not None else None
                if v is not None:
                    values.setdefault(m.findtext("name", "").strip(), v)
            if m.get("kind") != "enum":
                continue
            nxt = 0
            for ev in m.findall("enumvalue"):
                name = ev.findtext("name", "").strip()
                init = _text(ev.find("initializer")).lstrip("=").strip()
                if init:
                    v = _eval(init, values)
                    nxt = v if v is not None else nxt
                values.setdefault(name, nxt)
                nxt += 1
    return values


# --------------------------------------------------------------------------
# Header pages
# --------------------------------------------------------------------------
def file_compounds(xmldir: Path) -> dict[str, ET.Element]:
    out: dict[str, ET.Element] = {}
    for f in sorted(xmldir.glob("*_8h.xml")):
        cd = ET.parse(f).getroot().find("compounddef")
        loc = cd.find("location")
        if loc is not None and loc.get("file"):
            out[loc.get("file")] = cd
    return out


def members(cd: ET.Element, kind: str) -> list[ET.Element]:
    return [m for sec in cd.findall("sectiondef") for m in sec.findall("memberdef")
            if m.get("kind") == kind and not (m.findtext("name") or "").startswith("_")
            and not (m.get("kind") == "define" and (m.findtext("name") or "").endswith("_H"))]


def struct_compound(xmldir: Path, refid: str) -> ET.Element | None:
    path = xmldir / f"{refid}.xml"
    return ET.parse(path).getroot().find("compounddef") if path.exists() else None


def register_header(cd: ET.Element, page: Path, xmldir: Path) -> None:
    for kind in ("typedef", "define", "function", "enum"):
        for m in members(cd, kind):
            name = m.findtext("name", "").strip()
            if kind == "typedef" and (m.findtext("type") or "").strip().startswith(("struct", "enum")):
                continue
            LINKS.setdefault(name, (page, name.lower()))
            if kind == "enum":
                for ev in m.findall("enumvalue"):
                    LINKS.setdefault(ev.findtext("name", "").strip(), (page, name.lower()))
    for ic in cd.findall("innerclass"):
        LINKS.setdefault(ic.text, (page, ic.text.lower()))


def is_anon_alias(m: ET.Element) -> bool:
    return "@" in _text(m.find("type"))


def render_header(cd: ET.Element, page: Path, title: str, xmldir: Path,
                  values: dict[str, int]) -> str:
    if page.is_relative_to(LIB):
        title = f"`<{title}>`"
    global CUR
    CUR = page
    body: list[str] = []
    brief = _inline(cd.find("briefdescription"))
    if brief:
        body += [brief, ""]
    detail = flatten(cd.find("detaileddescription"))
    if detail:
        body += [detail, ""]
    loc = cd.find("location").get("file")
    body += [f"```c\n#include <{loc.removeprefix('include/')}>\n```", ""]

    enums = {m.findtext("name", "").strip(): m for m in members(cd, "enum")}
    typedefs = [m for m in members(cd, "typedef") if not is_anon_alias(m)]
    scalars = [m for m in typedefs if m.findtext("name", "").strip() not in enums]
    if scalars:
        body += ["## Types", "", md_table(["Type", "Definition", "Description"], [
            (f'<a id="{m.findtext("name").strip().lower()}"></a>`{m.findtext("name").strip()}`',
             f'`{_text(m.find("type"))}`', _desc(m)) for m in scalars]), ""]

    defines = members(cd, "define")
    if defines:
        body += ["## Constants", "", md_table(["Name", "Value", "Description"], [
            (f'<a id="{m.findtext("name").strip().lower()}"></a>`{proto_of(m).removeprefix("#define ")}`',
             f'`{_text(m.find("initializer"))}`' if m.find("initializer") is not None else "",
             _desc(m)) for m in defines]), ""]

    if enums:
        body += ["## Enumerations", ""]
        for name, m in enums.items():
            label = name if not name.startswith("@") else ""
            alias = next((t.findtext("name").strip() for t in members(cd, "typedef")
                          if _text(t.find("type")).endswith(name)), label)
            body += [f"### `{alias}` {{ #{alias.lower()} }}", "", _desc(m), "",
                     md_table(["Name", "Value", "Description"], [
                         (f"`{ev.findtext('name').strip()}`",
                          f"`{values[ev.findtext('name').strip()]}`" if ev.findtext("name").strip() in values else "",
                          _desc(ev)) for ev in m.findall("enumvalue")]), ""]

    structs = [(ic.text, struct_compound(xmldir, ic.get("refid", ""))) for ic in cd.findall("innerclass")]
    structs = [(n, s) for n, s in structs if s is not None]
    if structs:
        body += ["## Structures", ""]
        for name, s in structs:
            fields = [m for m in s.iter("memberdef") if m.get("kind") == "variable"]
            body += [f"### `{name}` {{ #{name.lower()} }}", "", _desc(s), "",
                     md_table(["Field", "Type", "Description"], [
                         (f"`{f.findtext('name').strip()}`", _type(f.find("type")), _desc(f))
                         for f in fields]), ""]

    funcs = [m for m in members(cd, "function") if m.get("static") != "yes"]
    if funcs:
        body += ["## Functions", ""]
        for m in funcs:
            body += [render_function(m, level=3), ""]

    return page_text(title, body)


def render_function(m: ET.Element, level: int) -> str:
    dd = m.find("detaileddescription")
    name = m.findtext("name", "").strip()
    h = "#" * level
    parts = [f"{h} `{name}` {{ #{name.lower()} }}", "", "```c", proto_of(m) + ";", "```", ""]
    brief = _inline(m.find("briefdescription"))
    if brief:
        parts += [brief, ""]
    prose = _prose(dd)
    if prose:
        parts += [prose, ""]
    params = _param_pairs(dd, "param")
    if params:
        parts += [md_table(["Parameter", "Direction", "Description"],
                           [(f"`{n}`", d or "in", t) for n, d, t in params]), ""]
    ret = _return(dd)
    if ret:
        parts += [f"**Returns:** {ret}", ""]
    errors = [(n, t) for n, _, t in _param_pairs(dd, "retval") if n != "ZUZU_OK"]
    if errors:
        parts += [md_table(["Error", "Condition"], [(link(n, f"`{n}`"), t) for n, t in errors]), ""]
    parts += _admonitions(dd)
    return "\n".join(parts).rstrip()


# --------------------------------------------------------------------------
# Syscalls
# --------------------------------------------------------------------------
def xrefs(dd: ET.Element | None) -> dict[str, str]:
    out: dict[str, str] = {}
    if dd is None:
        return out
    for xs in dd.iter("xrefsect"):
        key = (xs.get("id") or "").split("_1_", 1)[0]
        out[key] = _text(xs.find("xrefdescription"))
    return out


def annotate(text: str, values: dict[str, int]) -> str:
    return re.sub(r"\b[A-Z][A-Z0-9_]+\b",
                  lambda mo: f"{mo.group(0)} ({values[mo.group(0)]})" if mo.group(0) in values else mo.group(0),
                  text)


class Syscall:
    def __init__(self, m: ET.Element, group: str, values: dict[str, int]):
        self.m = m
        self.name = m.findtext("name", "").strip()
        self.group = group
        self.refs = xrefs(m.find("detaileddescription"))
        self.helper = "syscall_num" not in self.refs
        self.number = None
        self.svc = self.selector = ""
        if not self.helper:
            svc, _, rest = self.refs["syscall_num"].partition(" ")
            rest = rest.strip().removeprefix("/").strip()
            if svc not in values:
                raise SystemExit(f"error: {self.name}: unknown syscall number {svc}")
            self.number, self.svc, self.selector = values[svc], svc, annotate(rest, values)
        self.page = SYSCALLS / f"{self.name.lower()}.md"


def collect_syscalls(xmldir: Path, values: dict[str, int]) -> list[Syscall]:
    calls: list[Syscall] = []
    for f in sorted(xmldir.glob("group__syscalls__*.xml")):
        group = ET.parse(f).getroot().find("compounddef")
        gname = group.get("id", "").removeprefix("group__syscalls__")
        for m in group.iter("memberdef"):
            if m.get("kind") == "function":
                calls.append(Syscall(m, gname, values))
    return calls


def render_syscall(sc: Syscall) -> str:
    global CUR
    CUR = sc.page
    m, dd = sc.m, sc.m.find("detaileddescription")
    body: list[str] = []
    brief = _inline(m.find("briefdescription"))
    if brief:
        body += [brief, ""]
    if sc.helper:
        body += ['!!! info "Library helper"',
                 "    Implemented in `zuzu.h` on top of the syscalls; it has no syscall number of its own.", ""]
    else:
        row = [f"`0x{sc.number:02X}` {sc.svc}", f"`{sc.selector}`" if sc.selector else "—",
               sc.refs.get("syscall_blocking", ""), SINCE]
        body += [md_table(["Number", "Selector", "Blocking", "Since"], [tuple(row)]), ""]
    body += ["```c", proto_of(m) + ";", "```", ""]
    if not sc.helper and sc.refs.get("syscall_sig"):
        body += [f"**Registers:** `{sc.refs['syscall_sig']}`", ""]
    prose = _prose(dd)
    if prose:
        body += [prose, ""]
    params = _param_pairs(dd, "param")
    if params:
        body += ["## Parameters", "", md_table(["Name", "Direction", "Description"],
                                               [(f"`{n}`", d or "in", t) for n, d, t in params]), ""]
    ret = _return(dd)
    if ret:
        body += ["## Returns", "", ret, ""]
    errors = [(n, t) for n, _, t in _param_pairs(dd, "retval") if n != "ZUZU_OK"]
    if errors:
        body += ["## Errors", "", md_table(["Error", "Condition"],
                                           [(link(n, f"`{n}`"), t) for n, t in errors]), ""]
    body += _admonitions(dd)
    return page_text(sc.name, body)


def render_syscall_index(calls: list[Syscall]) -> str:
    global CUR
    CUR = SYSCALLS / "index.md"
    body = ["Every function in `<zuzu/zuzu.h>`, grouped as in the header. Syscalls are "
            "listed by number; library helpers built on them follow each group.", ""]
    for key, title in GROUPS:
        items = [c for c in calls if c.group == key]
        items = sorted((c for c in items if not c.helper), key=lambda c: (c.number, c.name)) + \
            sorted((c for c in items if c.helper), key=lambda c: c.name)
        if not items:
            continue
        rows = [(f"`0x{c.number:02X}`" if not c.helper else "helper",
                 f"[`{c.name}`]({c.page.name})",
                 f"`{c.selector}`" if c.selector else "",
                 _inline(c.m.find("briefdescription"))) for c in items]
        body += [f"## {title}", "", md_table(["Number", "Name", "Selector", "Summary"], rows), ""]
    return page_text("Syscalls", body)


# --------------------------------------------------------------------------
def build(xmldir: Path) -> dict[Path, str]:
    values = enum_values(xmldir)
    files = file_compounds(xmldir)
    calls = collect_syscalls(xmldir, values)

    headers: list[tuple[ET.Element, Path, str]] = []
    for path, (page, title) in HEADERS.items():
        if path in files:
            headers.append((files[path], page, title))
    libs: list[tuple[ET.Element, Path, str]] = []
    for path, cd in files.items():
        if path in HEADERS or path in NO_PAGE or not path.startswith("include/"):
            continue
        if path.startswith("include/sync/"):
            if Path(path).name not in SYNC_SKIP:
                classes = [ic.text for ic in cd.findall("innerclass")]
                title = classes[0] if len(classes) == 1 else Path(path).stem
                headers.append((cd, SYNC / f"{Path(path).stem}.md", title))
            continue
        rel = Path(path).relative_to("include")
        libs.append((cd, LIB / rel.with_suffix(".md"), str(rel)))
    headers += libs

    for sc in calls:
        LINKS[sc.name] = (sc.page, "")
    for cd, page, _ in headers:
        register_header(cd, page, xmldir)

    pages = {sc.page: render_syscall(sc) for sc in calls}
    pages[SYSCALLS / "index.md"] = render_syscall_index(calls)
    for cd, page, title in headers:
        pages[page] = render_header(cd, page, title, xmldir, values)
    pages[LIB / "index.md"] = render_lib_index(libs)
    return pages


def render_lib_index(libs: list[tuple[ET.Element, Path, str]]) -> str:
    global CUR
    CUR = LIB / "index.md"
    body = ["The support libraries in `include/`. Each header that is listed in "
            "`docs/doc-publish` in the zuzu repository gets a page here.", ""]
    by_dir: dict[str, list[tuple[ET.Element, Path, str]]] = {}
    for item in sorted(libs, key=lambda t: t[2]):
        by_dir.setdefault(str(Path(item[2]).parent), []).append(item)
    for d, items in by_dir.items():
        rows = [(f"[`<{title}>`]({os.path.relpath(page, CUR.parent)})",
                 _inline(cd.find("briefdescription"))) for cd, page, title in items]
        body += [f"## {d}/", "", md_table(["Header", "Summary"], rows), ""]
    return page_text("Libraries", body)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--xml", default=Path("docs/doxygen/xml"), type=Path)
    ap.add_argument("--out", default=Path("../zuzu-docs"), type=Path)
    ap.add_argument("--check", action="store_true",
                    help="exit 1 if any output would change (drift check)")
    ap.add_argument("--clean", action="store_true",
                    help="delete generated pages that have no source")
    args = ap.parse_args()

    if not (args.xml / "index.xml").exists():
        print(f"error: {args.xml}/index.xml not found -- run doxygen first", file=sys.stderr)
        return 2

    pages = build(args.xml)
    drift = False
    for rel, text in sorted(pages.items()):
        dest = args.out / rel
        old = dest.read_text() if dest.exists() else None
        changed = old != text
        drift |= changed
        if changed and not args.check:
            dest.parent.mkdir(parents=True, exist_ok=True)
            dest.write_text(text)
        print(f"{'DRIFT ' if changed else 'ok    '}{rel}")

    if args.clean:
        owned = {SYSCALLS, SYNC, LIB}
        for d in owned:
            for stale in sorted((args.out / d).rglob("*.md")):
                if stale.relative_to(args.out) in pages:
                    continue
                drift = True
                if not args.check:
                    stale.unlink()
                print(f"STALE {stale.relative_to(args.out)}")

    if args.check and drift:
        print("\nerror: generated docs are stale -- run make docs-site", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
