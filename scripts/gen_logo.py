#!/usr/bin/env python3
"""Turns docs/img/zuzu-logo.png into an 8-bit coverage mask C header for wm."""
import sys
from PIL import Image, ImageOps

src, dst, height = sys.argv[1], sys.argv[2], int(sys.argv[3])
img = ImageOps.invert(Image.open(src).convert("L"))
img = img.crop(img.getbbox())
width = round(img.width * height / img.height)
img = img.resize((width, height), Image.LANCZOS)
data = img.tobytes()
with open(dst, "w") as f:
    f.write("/* Generated by scripts/gen_logo.py from docs/img/zuzu-logo.png; do not edit. */\n")
    f.write("#ifndef WM_LOGO_H\n#define WM_LOGO_H\n\n#include <stdint.h>\n\n")
    f.write(f"#define LOGO_W {width}\n#define LOGO_H {height}\n\n")
    f.write("static const uint8_t k_logo[LOGO_W * LOGO_H] = {\n")
    for i in range(0, len(data), 24):
        f.write("    " + ", ".join(str(b) for b in data[i:i + 24]) + ",\n")
    f.write("};\n\n#endif /* WM_LOGO_H */\n")
